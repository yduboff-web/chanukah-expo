import {readFileSync} from 'node:fs';
import {initializeTestEnvironment,assertFails,assertSucceeds} from '@firebase/rules-unit-testing';
import {doc,setDoc,getDoc,getDocs,collection,updateDoc,deleteDoc,serverTimestamp,Timestamp} from 'firebase/firestore';
const env=await initializeTestEnvironment({projectId:'demo-expo',firestore:{rules:readFileSync(new URL('../firestore.rules',import.meta.url),'utf8')}});
const db=env.unauthenticatedContext().firestore();
const id='abcdef0123456789abcdef0123456789';const room=doc(db,'readingSessions',id);
const data=()=>({passage:'blessing1-ash',marks:[],elapsedMs:0,startedAt:null,createdAt:serverTimestamp(),updatedAt:serverTimestamp(),expiresAt:Timestamp.fromMillis(Date.now()+119*60000)});
let count=0;async function ok(name,p,pass){await(pass?assertSucceeds(p):assertFails(p));console.log('ok',name);count++;}
await env.clearFirestore();
await ok('anonymous valid room creation',setDoc(room,data()),true);
await ok('room known id readable',getDoc(room),true);
await ok('rooms cannot be listed',getDocs(collection(db,'readingSessions')),false);
await ok('marks shared',updateDoc(room,{marks:[0,2,7],updatedAt:serverTimestamp()}),true);
await ok('invalid word rejected',updateDoc(room,{marks:[300],updatedAt:serverTimestamp()}),false);
await ok('string word rejected',updateDoc(room,{marks:['name'],updatedAt:serverTimestamp()}),false);
await ok('name field rejected',updateDoc(room,{name:'someone',updatedAt:serverTimestamp()}),false);
await ok('timer starts',updateDoc(room,{startedAt:Timestamp.now(),updatedAt:serverTimestamp()}),true);
await ok('negative time rejected',updateDoc(room,{elapsedMs:-1,updatedAt:serverTimestamp()}),false);
await ok('oversized time rejected',updateDoc(room,{elapsedMs:7200001,updatedAt:serverTimestamp()}),false);
await ok('passage locked',updateDoc(room,{passage:'hanerot',updatedAt:serverTimestamp()}),false);
await ok('expiry cannot be extended',updateDoc(room,{expiresAt:Timestamp.fromMillis(Date.now()+86400000),updatedAt:serverTimestamp()}),false);
await ok('short code rejected',setDoc(doc(db,'readingSessions','123'),data()),false);
await ok('unknown passage rejected',setDoc(doc(db,'readingSessions','11111111111111111111111111111111'),{...data(),passage:'free-text'}),false);
await ok('long lifetime rejected',setDoc(doc(db,'readingSessions','22222222222222222222222222222222'),{...data(),expiresAt:Timestamp.fromMillis(Date.now()+86400000)}),false);
await env.withSecurityRulesDisabled(async c=>setDoc(doc(c.firestore(),'readingSessions','eeeeeeeeeeeeeeeeeeeeeeeeeeeeeeee'),{...data(),createdAt:new Date(),updatedAt:new Date(),expiresAt:Timestamp.fromMillis(Date.now()-1000)}));
const expired=doc(db,'readingSessions','eeeeeeeeeeeeeeeeeeeeeeeeeeeeeeee');
await ok('expired room cannot be read',getDoc(expired),false);
await ok('expired room cannot be changed',updateDoc(expired,{marks:[1],updatedAt:serverTimestamp()}),false);
await ok('room cannot open group data',getDoc(doc(db,'groups','oil4')),false);
await ok('close removes room',deleteDoc(room),true);
console.log(count+' reading-session tests passed');await env.cleanup();
